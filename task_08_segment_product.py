# Задача 8. Произведение длин отрезков AC и BC.
# По условию точка C расположена между точками A и B.

# Ввод координат точек на числовой оси.
a = float(input("Введите координату точки A: "))
b = float(input("Введите координату точки B: "))
c = float(input("Введите координату точки C (между A и B): "))

# Вычисление длин отрезков и их произведения.
AC = abs(c - a)
BC = abs(b - c)
segment_product = AC * BC

# Вывод результата.
print("Произведение длин отрезков AC и BC =", segment_product)
