# Задача 7. Длины отрезков AC и BC и их сумма на числовой оси.

# Ввод координат точек на числовой оси.
a = float(input("Введите координату точки A: "))
b = float(input("Введите координату точки B: "))
c = float(input("Введите координату точки C: "))

# Вычисление длин отрезков.
AC = abs(c - a)
BC = abs(c - b)
segments_sum = AC + BC

# Вывод результатов.
print("Длина отрезка AC =", AC)
print("Длина отрезка BC =", BC)
print("Сумма длин отрезков AC и BC =", segments_sum)
