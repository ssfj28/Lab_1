# Задача 10. Периметр и площадь треугольника по координатам вершин.

from math import sqrt

# Ввод координат трех вершин треугольника.
x1 = float(input("Введите координату x1 точки A: "))
y1 = float(input("Введите координату y1 точки A: "))
x2 = float(input("Введите координату x2 точки B: "))
y2 = float(input("Введите координату y2 точки B: "))
x3 = float(input("Введите координату x3 точки C: "))
y3 = float(input("Введите координату y3 точки C: "))

# Вычисление длин сторон по формуле расстояния между точками.
AB = sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2)
BC = sqrt((x3 - x2) ** 2 + (y3 - y2) ** 2)
CA = sqrt((x1 - x3) ** 2 + (y1 - y3) ** 2)

# Вычисление периметра и площади по координатной формуле.
P = AB + BC + CA
S = abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2

# Вывод результатов.
print("Периметр треугольника P =", P)
print("Площадь треугольника S =", S)
