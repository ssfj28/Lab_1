# Задача 9. Периметр и площадь прямоугольника по координатам
# двух противоположных вершин. Стороны параллельны осям координат.

# Ввод координат противоположных вершин.
x1 = float(input("Введите координату x1 первой вершины: "))
y1 = float(input("Введите координату y1 первой вершины: "))
x2 = float(input("Введите координату x2 второй вершины: "))
y2 = float(input("Введите координату y2 второй вершины: "))

# Вычисление длин сторон прямоугольника.
width = abs(x2 - x1)
height = abs(y2 - y1)

# Вычисление площади и периметра.
S = width * height
P = 2 * (width + height)

# Вывод результатов.
print("Площадь прямоугольника S =", S)
print("Периметр прямоугольника P =", P)
